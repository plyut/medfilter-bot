def parse_json(reply: str) -> dict:
    """Достаёт JSON из ответа модели: целиком, из ```-блока или от первой { до последней }."""
    candidates = [reply]
    fence = re.search(r"```(?:json)?\s*(.*?)```", reply, re.S)
    if fence:
        candidates.append(fence.group(1))
    if "{" in reply and "}" in reply:
        candidates.append(reply[reply.index("{"): reply.rindex("}") + 1])
    for c in candidates:
        try:
            data = json.loads(c)
        except (json.JSONDecodeError, TypeError):
            continue
        if isinstance(data, dict):
            return data
    raise ValueError("Нейросеть вернула ответ не в формате JSON")

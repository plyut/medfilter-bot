def claim_block(claim: dict) -> str:
    lines = [f"Утверждение: {claim.get('claim', '')}"]
    if claim.get("quote"):
        lines.append(f"Цитата из материала: «{claim['quote']}»")
    if claim.get("hedge"):
        lines.append(f"Оговорка автора: {claim['hedge']}")
    lines.append(f"Текущий вердикт: {claim.get('verdict', 'none')}; УДД {claim.get('udd', '?')}; "
                 f"уверенность {claim.get('confidence', '?')}")
    if claim.get("explanation"):
        lines.append(f"Обоснование текущего вердикта: {claim['explanation']}")
    srcs = ", ".join(f"{s.get('id')}: {s.get('query')}" for s in claim.get("sources") or [] if isinstance(s, dict))
    if srcs:
        lines.append(f"Исходные источники: {srcs}")
    return "\n".join(lines)


def build_appeal_prompt(title: str, claim: dict, reason: str, argument: str, source_text: str,
                        screenshot_text: str) -> str:
    return f"""Сегодня {date.today():%d.%m.%Y}.
Материал: {title or 'без названия'}

ИСХОДНАЯ ПРОВЕРКА
{claim_block(claim)}

АПЕЛЛЯЦИЯ ПОЛЬЗОВАТЕЛЯ
Причина несогласия: {reason}
Доводы пользователя:
\"\"\"
{argument or '(доводы не приложены)'}
\"\"\"

НОВЫЙ ИСТОЧНИК
{source_text or 'Пользователь оспаривает вердикт без источника.'}

СКРИНШОТ ОТ ПОЛЬЗОВАТЕЛЯ
{screenshot_text or 'нет'}"""



"""Распознавание личных медицинских документов (выписки, анализы, рецепты).

Бот такие документы не принимает: это персональные данные о здоровье (особая категория
по 152-ФЗ), а проверять он должен публичные утверждения, а не диагноз конкретного человека.
Документ узнаём по сочетанию характерных признаков: одно слово «анализ» в посте о здоровье
не считается, нужны минимум два разных признака бланка.
"""
import re

_MARKERS = [
    r"выписн\w* эпикриз", r"\bэпикриз", r"медицинск\w+ карт\w*", r"история болезни",
    r"\bф\.?\s?и\.?\s?о\.?\s*(пациента|больного)", r"(пациент|больн(ой|ая))\s*:", r"дата рождения",
    r"полис\w*\s*(омс|дмс)", r"\bомс\b\s*№", r"№\s*карты",
    r"референсн\w+ (значени|интервал)", r"\bнорма\b.{0,30}\bрезультат", r"результат\w*.{0,30}\bнорма\b",
    r"заключение врача", r"\bдиагноз\s*:", r"\bмкб[- ]?10", r"лечащий врач", r"\bрецепт\w*\s*(№|форма)",
    r"направление на", r"лабораторн\w+ (исследовани|анализ)\w*.{0,40}(дата|№)",
]
_RE = [re.compile(m, re.I | re.S) for m in _MARKERS]


def looks_like_medical_document(text: str) -> bool:
    text = text or ""
    hits = sum(1 for r in _RE if r.search(text))
    return hits >= 2


